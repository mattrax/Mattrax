import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import type { Collection, PlatformData } from "./catalog";
import {
  APPLE_DECLARATION_DOCS,
  APPLE_DEVICE_MANAGEMENT_DOCS,
  APPLE_PROFILE_DOCS,
  WINDOWS_CSP_DOCS,
  appleDocumentationUrl,
  applePayloadDocumentationUrl,
  collectionDocumentationUrl,
  isApplePayloadType,
  propertyDocumentationUrl,
  windowsCollectionDocumentationUrl,
  windowsPropertyDocumentationUrl,
} from "./documentation";
import { thirdPartyAppCollectionId } from "./thirdPartyApps";

// SAFETY: both files are generated by `catalog:sync` and decoded by the
// catalogue loaders at runtime; the assertions below only read known fields.
const apple = JSON.parse(
  readFileSync(
    fileURLToPath(new URL("../../../public/catalog/apple.json", import.meta.url)),
    "utf8",
  ),
) as PlatformData;

// SAFETY: see above; `windows.json` is the source the split catalogue is built
// from.
const windows = JSON.parse(
  readFileSync(
    fileURLToPath(new URL("../../../../../data/catalog/windows.json", import.meta.url)),
    "utf8",
  ),
) as PlatformData;

const profile = (
  identifier: string,
  name = identifier,
): Pick<Collection, "kind" | "identifier" | "name"> => ({
  kind: "profile",
  identifier,
  name,
});

const declaration = (identifier: string): Pick<Collection, "kind" | "identifier" | "name"> => ({
  kind: "declaration",
  identifier,
  name: identifier,
});

describe("Apple documentation links", () => {
  it("links a profile payload to its developer.apple.com page", () => {
    expect(appleDocumentationUrl(profile("com.apple.applicationaccess", "Restrictions"))).toBe(
      "https://developer.apple.com/documentation/devicemanagement/restrictions",
    );
    expect(appleDocumentationUrl(profile("com.apple.wifi.managed", "Wi-Fi"))).toBe(
      "https://developer.apple.com/documentation/devicemanagement/wifi",
    );
  });

  it("uses the collection name when Apple documents a type more than once", () => {
    expect(appleDocumentationUrl(profile("com.apple.MCX", "Accounts"))).toBe(
      "https://developer.apple.com/documentation/devicemanagement/accounts",
    );
    expect(appleDocumentationUrl(profile("com.apple.MCX", "Time Server"))).toBe(
      "https://developer.apple.com/documentation/devicemanagement/timeserver",
    );
    expect(
      appleDocumentationUrl(profile("com.apple.extensiblesso", "Extensible Single Sign-On")),
    ).toBe("https://developer.apple.com/documentation/devicemanagement/extensiblesinglesignon");
    expect(
      appleDocumentationUrl(
        profile("com.apple.extensiblesso", "Extensible Single Sign-On (Kerberos)"),
      ),
    ).toBe(
      "https://developer.apple.com/documentation/devicemanagement/extensiblesinglesignonkerberos",
    );
  });

  it("links DDM declarations to their developer.apple.com page", () => {
    expect(appleDocumentationUrl(declaration("com.apple.configuration.passcode.settings"))).toBe(
      "https://developer.apple.com/documentation/devicemanagement/passcodesettings",
    );
    expect(appleDocumentationUrl(declaration("com.apple.management.properties"))).toBe(
      "https://developer.apple.com/documentation/devicemanagement/managementproperties",
    );
  });

  it("falls back to an index page for unknown types instead of guessing a URL", () => {
    expect(appleDocumentationUrl(profile("com.example.custom", "Custom Payload"))).toBe(
      APPLE_PROFILE_DOCS,
    );
    expect(appleDocumentationUrl(declaration("com.example.custom"))).toBe(APPLE_DECLARATION_DOCS);
    expect(appleDocumentationUrl({ kind: "csp", identifier: "unknown", name: "Unknown" })).toBe(
      APPLE_DEVICE_MANAGEMENT_DOCS,
    );
  });

  it("resolves raw PayloadType values from uploaded profiles", () => {
    expect(applePayloadDocumentationUrl("com.apple.mobiledevice.passwordpolicy")).toBe(
      "https://developer.apple.com/documentation/devicemanagement/passcode",
    );
    expect(applePayloadDocumentationUrl("Configuration")).toBe(APPLE_PROFILE_DOCS);
    // An Apple payload Apple does not document still gets the safe index page.
    expect(applePayloadDocumentationUrl("com.apple.example.custom")).toBe(APPLE_PROFILE_DOCS);
    expect(applePayloadDocumentationUrl(undefined)).toBeUndefined();
  });

  it("does not claim third-party payloads as Apple documentation", () => {
    expect(applePayloadDocumentationUrl("com.google.Chrome")).toBeUndefined();
    expect(isApplePayloadType("com.apple.wifi.managed")).toBe(true);
    expect(isApplePayloadType("Configuration")).toBe(true);
    expect(isApplePayloadType("com.google.Chrome")).toBe(false);
    expect(isApplePayloadType(undefined)).toBe(false);
  });

  it("maps every current catalogue entry to a valid developer.apple.com URL", () => {
    // Apple no longer publishes pages for these legacy payloads, so they
    // deliberately use the index fallback.
    const legacyProfiles = new Set([
      "com.apple.AIM.account",
      "com.apple.dashboard",
      "com.apple.jabber.account",
      "com.apple.osxserver.account",
    ]);

    for (const collection of apple.collections) {
      const url = appleDocumentationUrl(collection);

      expect(url.startsWith("https://developer.apple.com/documentation/devicemanagement")).toBe(
        true,
      );

      if (collection.kind === "declaration") {
        expect(url).not.toBe(APPLE_DECLARATION_DOCS);
        expect(url).not.toBe(APPLE_PROFILE_DOCS);
      }

      if (collection.kind === "profile" && !legacyProfiles.has(collection.identifier))
        expect(url).not.toBe(APPLE_PROFILE_DOCS);
    }
  });
});

describe("Windows documentation links", () => {
  it("prefers the property source from the catalogue", () => {
    const propertySource =
      "https://learn.microsoft.com/en-us/windows/client-management/mdm/policy-csp-abovelock#allowcortanaabovelock";

    expect(windowsPropertyDocumentationUrl("https://example.com/collection", propertySource)).toBe(
      propertySource,
    );
  });

  it("falls back to the collection source and then Microsoft's CSP reference", () => {
    const collectionSource =
      "https://learn.microsoft.com/en-us/windows/client-management/mdm/configuration-service-provider-reference";

    expect(windowsPropertyDocumentationUrl(collectionSource, undefined)).toBe(collectionSource);
    expect(windowsPropertyDocumentationUrl(undefined, undefined)).toBe(WINDOWS_CSP_DOCS);
    expect(windowsCollectionDocumentationUrl(undefined)).toBe(WINDOWS_CSP_DOCS);
  });

  it("rejects unsafe or malformed source URLs", () => {
    expect(
      windowsPropertyDocumentationUrl("https://example.com/collection", "javascript:alert(1)"),
    ).toBe("https://example.com/collection");
    expect(windowsPropertyDocumentationUrl("http://example.com", "not a url")).toBe(
      WINDOWS_CSP_DOCS,
    );
  });

  it("only offers links for Windows settings, not Apple's per-setting rows", () => {
    expect(
      propertyDocumentationUrl("apple", { source: "https://example.com" }, undefined),
    ).toBeUndefined();
    expect(collectionDocumentationUrl("android", profile("android"))).toBeUndefined();
  });

  it("hides the generic CSP link for third-party Windows settings", () => {
    const propertySource =
      "https://learn.microsoft.com/en-us/windows/client-management/mdm/policy-csp-restrictedgroups";

    expect(
      propertyDocumentationUrl(
        "windows",
        { source: propertySource },
        WINDOWS_CSP_DOCS,
        thirdPartyAppCollectionId("windows", "chrome"),
      ),
    ).toBeUndefined();
    expect(
      propertyDocumentationUrl(
        "windows",
        { source: propertySource },
        WINDOWS_CSP_DOCS,
        "windows/settings/restricted-groups",
      ),
    ).toBe(propertySource);
  });

  it("uses the catalogue's own sources for every Windows collection and property", () => {
    for (const collection of windows.collections) {
      const collectionUrl = collectionDocumentationUrl("windows", collection);

      expect(collectionUrl).toBe(collection.source);

      for (const property of collection.properties) {
        const url = propertyDocumentationUrl("windows", property, collection.source);

        expect(url).toBe(property.source ?? collection.source);
      }
    }
  });
});
