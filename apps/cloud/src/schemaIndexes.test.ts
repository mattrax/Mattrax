import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * Index-shape guarantees for the query paths that matter.
 *
 * These read the latest migration snapshot rather than the TypeScript schema,
 * so a change is only accepted once it has been generated and applied. Each
 * assertion names the query it protects; see
 * `docs/reference/architecture.md` ("Data model").
 */

const migrationsDir = join(import.meta.dirname, "..", "migrations");

type SnapshotIndex = {
  readonly entityType: "indexes" | "pks";
  readonly table: string;
  readonly name: string;
  readonly columns: ReadonlyArray<string | { readonly value: string }>;
  readonly isUnique?: boolean;
};

type Snapshot = { readonly ddl: ReadonlyArray<SnapshotIndex> };

const latestSnapshot = (): Snapshot => {
  const names = readdirSync(migrationsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

  return JSON.parse(readFileSync(join(migrationsDir, names.at(-1)!, "snapshot.json"), "utf8"));
};

const columnNames = (index: SnapshotIndex): ReadonlyArray<string> =>
  // oxlint-disable-next-line anti-slop/no-runtime-typeof -- snapshot columns are a string-or-object union.
  index.columns.map((column) => (typeof column === "string" ? column : column.value));

const indexLookup = () => {
  const byTable = new Map<string, SnapshotIndex[]>();

  for (const entry of latestSnapshot().ddl) {
    if (entry.entityType !== "indexes" && entry.entityType !== "pks") continue;

    const list = byTable.get(entry.table) ?? [];
    list.push(entry);
    byTable.set(entry.table, list);
  }

  return byTable;
};

const hasIndex = (table: string, columns: ReadonlyArray<string>): boolean =>
  (indexLookup().get(table) ?? []).some((index) => columnNames(index).join(",") === columns.join(","));

/**
 * The auth tables (`auth_*`) are generated by `@yielded/auth` and their index
 * names are part of that contract; the application does not own them.
 */
const LIBRARY_TABLES = new Set([
  "auth_credentials",
  "auth_identifiers",
  "auth_passkeyCredentials",
  "auth_passkeyFlows",
  "auth_pending",
  "auth_sessions",
  "auth_totp_factor",
]);

describe("query-driven indexes", () => {
  it("indexes the Apple and Windows check-in identity lookup", () => {
    // `mdm-apple` findDeviceByScope and `mdm-windows` findDevice resolve every
    // check-in by protocol identifier; the per-tenant indexes cannot serve it.
    expect(hasIndex("device", ["dm_identifier"])).toBe(true);
    // Enrollment proves a departing device across tenants by protocol+serial.
    expect(hasIndex("device", ["proto", "serial"])).toBe(true);
  });

  it("indexes per-device command history by creation time", () => {
    // Device detail and both check-in paths read one device's commands
    // oldest- or newest-first. Without this the whole history is sorted.
    expect(hasIndex("device_command", ["device_id", "created_at"])).toBe(true);
    // The activity page uses a keyset on the update clock.
    expect(hasIndex("device_command", ["device_id", "updated_at"])).toBe(true);
  });

  it("indexes every retention sweep by its clock", () => {
    expect(hasIndex("audit_log", ["created_at"])).toBe(true);
    expect(hasIndex("account_audit_log", ["created_at"])).toBe(true);
    expect(hasIndex("enrollment_attempt", ["created_at"])).toBe(true);
    expect(hasIndex("webhook_delivery", ["created_at"])).toBe(true);
    expect(hasIndex("email_outbox", ["status", "created_at"])).toBe(true);
    expect(hasIndex("invitation", ["status", "expires_at"])).toBe(true);
    expect(hasIndex("android_pubsub_message", ["received_at"])).toBe(true);
  });
});

describe("no redundant index prefixes", () => {
  it("never declares an index whose columns are a prefix of another index on the table", () => {
    const redundant: string[] = [];

    for (const [table, indexes] of indexLookup()) {
      if (LIBRARY_TABLES.has(table)) continue;

      for (const index of indexes) {
        const columns = columnNames(index);

        const covered = indexes.some((other) => {
          if (other === index) return false;

          const otherColumns = columnNames(other);

          return (
            otherColumns.length > columns.length &&
            columns.every((column, position) => otherColumns[position] === column)
          );
        });

        // Exact duplicates (same columns, different name) are redundant too.
        const duplicated = indexes.some(
          (other) =>
            other !== index &&
            other.name !== index.name &&
            columnNames(other).join(",") === columns.join(",") &&
            other.entityType === index.entityType,
        );

        if (covered || duplicated)
          redundant.push(`${table}.${index.name} (${columns.join(", ")})`);
      }
    }

    expect(redundant).toEqual([]);
  });
});
