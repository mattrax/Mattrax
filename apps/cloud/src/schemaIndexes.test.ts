describe("query-driven indexes", () => {
  it("indexes the Apple and Windows check-in identity lookup", () => {
    // `mdm-apple` findDeviceByScope and `mdm-windows` findDevice resolve every
    // check-in by protocol identifier; the per-tenant indexes cannot serve it.
    expect(hasIndex("device", ["dm_identifier"])).toBe(true);
    // Enrollment proves a departing device across tenants by protocol+serial.
    expect(hasIndex("device", ["proto", "serial"])).toBe(true);
  });

  it("keeps the ordered fleet-list and export paths", () => {
    // The fleet list, global search and CSV export page per tenant by name.
    expect(hasIndex("device", ["organization_id", "name"])).toBe(true);
    // `sort=enrolledAt` (ascending by default) uses this ordered path.
    expect(hasIndex("device", ["organization_id", "enrolled_at"])).toBe(true);
    // The "last seen" sort and the stale-device filter.
    expect(hasIndex("device", ["organization_id", "last_seen_at"])).toBe(true);
  });

  it("indexes per-device command history by creation time", () => {
    // Device detail and both check-in paths read one device's commands
    // oldest- or newest-first. Without this the whole history is sorted.
    expect(hasIndex("device_command", ["device_id", "created_at"])).toBe(true);
    // The activity page uses a keyset on the update clock.
    expect(hasIndex("device_command", ["device_id", "updated_at"])).toBe(true);
  });

  it("indexes every retention sweep by its clock", () => {
    expect(hasIndex("audit_log", ["created_at"])).toBe(true);
    expect(hasIndex("account_audit_log", ["created_at"])).toBe(true);
    expect(hasIndex("enrollment_attempt", ["created_at"])).toBe(true);
    expect(hasIndex("webhook_delivery", ["created_at"])).toBe(true);
    expect(hasIndex("email_outbox", ["status", "created_at"])).toBe(true);
    expect(hasIndex("invitation", ["status", "expires_at"])).toBe(true);
    expect(hasIndex("android_pubsub_message", ["received_at"])).toBe(true);
    // Session expiry pages by both values, so mostly-live auth tables do not
    // fall back to a primary-key scan.
    expect(hasIndex("auth_sessions", ["expires_at", "session_id"])).toBe(true);
  });

  it("orders tenant-scoped audit filters by the keyset cursor", () => {
    // Search/export add one equality filter, then page by created_at DESC,
    // id DESC. The unfiltered tenant stream keeps its separate index.
    expect(hasIndex("audit_log", ["organization_id", "created_at"])).toBe(true);
    expect(hasIndex("audit_log", ["organization_id", "category", "created_at", "id"])).toBe(true);
    expect(hasIndex("audit_log", ["organization_id", "action", "created_at", "id"])).toBe(true);
    expect(hasIndex("audit_log", ["organization_id", "protocol", "created_at", "id"])).toBe(true);
    // The physical direction matters: MySQL otherwise prefers the unfiltered
    // tenant index for deep keyset ranges.
    expect(
      hasDescendingSuffix("audit_log", ["organization_id", "category", "created_at", "id"]),
    ).toBe(true);
    expect(
      hasDescendingSuffix("audit_log", ["organization_id", "action", "created_at", "id"]),
    ).toBe(true);
    expect(
      hasDescendingSuffix("audit_log", ["organization_id", "protocol", "created_at", "id"]),
    ).toBe(true);

    // The ordered action index replaces the old prefix; maintaining both
    // would add a second B-tree write to every audit insert.
    expect(hasIndex("audit_log", ["organization_id", "action"])).toBe(false);

    // Device activity already has a device-leading ordered path. Do not add a
    // second tenant/device composite that writes the same keys again.
    expect(hasIndex("audit_log", ["device_id", "organization_id", "created_at"])).toBe(true);
    expect(hasIndex("audit_log", ["organization_id", "device_id", "created_at", "id"])).toBe(false);
  });

  it("indexes the global stale-device and webhook retry queues", () => {
    // Maintenance is deployment-wide, so a tenant-leading index cannot serve
    // the stale-device predicate.
    expect(hasIndex("device", ["status", "last_seen_at"])).toBe(true);

    // Retry reads failed rows below the attempt cap, oldest first. Creation
    // time leads the residual attempt predicate so the queue is ordered without
    // a filesort; the old status/attempt prefix has no remaining reader.
    expect(hasIndex("webhook_delivery", ["status", "created_at", "attempt"])).toBe(true);
    expect(hasIndex("webhook_delivery", ["status", "attempt"])).toBe(false);
  });
});

describe("foreign-key index coverage", () => {
  it("covers every foreign key with a leading index, primary key or documented implicit index", () => {
    const byTable = indexesByTable();
    const uncovered = new Set<string>();

    for (const entry of latestSnapshot().ddl) {
      if (entry.entityType !== "fks") continue;

      const columns = columnNames(entry);

      const covered = (byTable.get(entry.table) ?? []).some((index) => {
        const indexColumns = columnNames(index);

        return columns.every((column, position) => indexColumns[position] === column);
      });

      if (!covered) uncovered.add(entry.name);
    }

    // A new foreign key must not silently rely on InnoDB's automatic index.
    expect([...uncovered].filter((name) => !INNODB_IMPLICIT_FK_INDEXES.has(name))).toEqual([]);

    // The exception list must not go stale when an explicit index is added.
    expect([...INNODB_IMPLICIT_FK_INDEXES].filter((name) => !uncovered.has(name))).toEqual([]);
  });
});

describe("no redundant index prefixes", () => {
  it("never declares an index whose columns are a prefix of another index on the table", () => {
    const redundant: string[] = [];

    for (const [table, indexes] of indexesByTable()) {
      if (LIBRARY_TABLES.has(table)) continue;

      for (const index of indexes) {
        const columns = columnNames(index);

        const covered = indexes.some((other) => {
          if (other === index) return false;

          const otherColumns = columnNames(other);

          return (
            otherColumns.length > columns.length &&
            columns.every((column, position) => otherColumns[position] === column)
          );
        });

        // Exact duplicates (same columns, different name) are redundant too.
        const duplicated = indexes.some(
          (other) =>
            other !== index &&
            other.name !== index.name &&
            columnNames(other).join(",") === columns.join(",") &&
            other.entityType === index.entityType,
        );

        if (covered || duplicated) redundant.push(`${table}.${index.name} (${columns.join(", ")})`);
      }
    }

    expect(redundant).toEqual([]);
  });
});
