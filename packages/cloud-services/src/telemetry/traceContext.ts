/**
 * W3C Trace Context support.
 *
 * `traceparent` is the only propagation format this deployment speaks: the
 * edge accepts it from a caller and the API Worker puts the same trace id on
 * every request log line and child span. `tracestate` is not interpreted (we
 * have no multi-vendor state to carry), so a caller's state is not echoed back.
 *
 * Spec: <https://www.w3.org/TR/trace-context/#traceparent-header>
 */

/** A parsed `traceparent` header. `spanId` is the *parent* span id. */
export type TraceContext = {
  readonly traceId: string;
  readonly spanId: string;
  readonly traceFlags: number;
  readonly sampled: boolean;
};

const VERSION_PATTERN = /^[0-9a-f]{2}$/;

const TRACE_ID_PATTERN = /^[0-9a-f]{32}$/;

const SPAN_ID_PATTERN = /^[0-9a-f]{16}$/;

const FLAGS_PATTERN = /^[0-9a-f]{2}$/;

const INVALID_VERSION = "ff";

const ZERO_TRACE_ID = "0".repeat(32);

const ZERO_SPAN_ID = "0".repeat(16);

/**
 * Parse a `traceparent` value.
 *
 * Returns `undefined` for anything the spec calls invalid: an unknown
 * version, `ff`, uppercase hex, all-zero ids, a short field or a `00`
 * header with extra fields. A hostile or garbage header therefore starts a new
 * trace instead of poisoning every span with a forged parent.
 */
export const parseTraceparent = (header: string | null | undefined): TraceContext | undefined => {
  if (!header) return undefined;

  // Do not lowercase: the spec calls uppercase hex invalid, and accepting it
  // would let two spellings of one trace id look like two traces.
  const parts = header.trim().split("-");

  const [version, traceId, spanId, flags, ...rest] = parts;

  if (version === undefined || !VERSION_PATTERN.test(version) || version === INVALID_VERSION)
    return undefined;

  // Version `00` is the only format defined so far and permits no trailing
  // fields. A future version may append data, which we ignore.
  if (version === "00" && rest.length > 0) return undefined;

  if (
    traceId === undefined ||
    !TRACE_ID_PATTERN.test(traceId) ||
    traceId === ZERO_TRACE_ID ||
    spanId === undefined ||
    !SPAN_ID_PATTERN.test(spanId) ||
    spanId === ZERO_SPAN_ID ||
    flags === undefined ||
    !FLAGS_PATTERN.test(flags)
  )
    return undefined;

  const traceFlags = Number.parseInt(flags, 16);

  return {
    traceId,
    spanId,
    traceFlags,
    // Bit 0 is the `sampled` flag.
    sampled: (traceFlags & 0x01) === 0x01,
  };
};

/** Format a context as a version `00` `traceparent` header. */
export const formatTraceparent = (context: TraceContext): string => {
  const flags = (context.traceFlags & 0xff).toString(16).padStart(2, "0");

  return `00-${context.traceId}-${context.spanId}-${flags}`;
};

/** A fresh context whose ids are generated by the deployment. */
export const newTraceContext = (options: { readonly sampled?: boolean } = {}): TraceContext => ({
  traceId: randomHex(32),
  spanId: randomHex(16),
  traceFlags: options.sampled === false ? 0 : 1,
  sampled: options.sampled !== false,
});

const randomHex = (length: number): string => {
  const bytes = new Uint8Array(length / 2);

  crypto.getRandomValues(bytes);

  return Array.from(bytes, (byte) => byte.toString(16).padStart(2, "0")).join("");
};
