/**
 * Yielded Auth owns identifiers, credentials, passwords, sessions, pending
 * authentication and password reset proofs. The application owns `user` above;
 * Yielded maps it as the subject table so user IDs remain stable.
 */
/**
 * Baseline assurance for accounts without a second factor. Accounts with an
 * authenticator app or a passkey use `authenticationRequirement(true)`.
 */
export const authRequirement: Sessions.AuthenticationRequirement = authenticationRequirement(false);

/** Whether an account has any factor that can satisfy multi-factor sign-in. */
export const hasMfaFactor = (subject: Readonly<Record<string, unknown>>): boolean =>
  subject.totpEnabled === true || subject.passkeyEnabled === true;

/** The sign-in requirement for one subject row. */
export const authRequirementForSubject = (
  subject: Readonly<Record<string, unknown>>,
): Sessions.AuthenticationRequirement => authenticationRequirement(hasMfaFactor(subject));

export const AuthPersistenceConfig: any = AuthPersistence.make(AuthDefinition);
