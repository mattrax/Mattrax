/**
 * MySQL stores indexes as key prefixes. Every column that participates in a
 * primary/unique index is therefore bounded; unbounded payloads stay `text`.
 */
const id = (name = "id") => varchar(name, { length: 255 });

const shortText = (name: string) => varchar(name, { length: 255 });

const timestamp = (name: string) => datetime(name, { mode: "date", fsp: 3 });

export const user = mysqlTable(
  "user",
  {
    id: id().primaryKey(),
    name: varchar("name", { length: 255 }).notNull(),
    email: varchar("email", { length: 320 }).notNull(),
    emailVerified: boolean("email_verified").notNull().default(false),
    image: text("image"),
    stripeCustomerId: shortText("stripe_customer_id"),
    /**
     * Account-level landing tenant, independent of the browser's last-used
     * tenant. Only honoured while the account is a member; membership loss
     * leaves the stale id here and both the API and the shell ignore it.
     */
    defaultTenantId: id("default_tenant_id").references(() => organization.id, {
      onDelete: "set null",
    }),
    disabled: boolean("disabled").notNull().default(false),
    /** Where this account came from; directory sync updates it on creation. */
    source: varchar("source", { length: 16, enum: ["manual", "scim", "graph"] })
      .notNull()
      .default("manual"),
    /**
     * Kept in sync by the TOTP persistence owner whenever an authenticator is
     * confirmed or disabled. Login requirements read this column.
     */
    totpEnabled: boolean("totp_enabled").notNull().default(false),
    /**
     * Kept in sync by the passkey lifecycle hook whenever this account gains or
     * loses its last active passkey. Together with `totpEnabled` this decides
     * whether sign-in requires a second factor.
     */
    passkeyEnabled: boolean("passkey_enabled").notNull().default(false),
    // Generated by the application during provisioning. MySQL has no
    // `gen_random_uuid()` default and non-deterministic defaults are rejected.
    authRevision: varchar("auth_revision", { length: 64 }).notNull(),
    /**
     * When the one-time welcome email was claimed and sent. The claim is an
     * atomic conditional update, so verification retries, concurrent requests
     * and the backstop sweep can never send it twice.
     */
    welcomeEmailSentAt: timestamp("welcome_email_sent_at"),
    createdAt: timestamp("created_at").notNull(),
    updatedAt: timestamp("updated_at").notNull(),
  },
  (table) => [
    uniqueIndex("user_email_unique").on(table.email),
    // Backstop sweep: manual + verified + unmarked, ordered by creation.
    index("user_welcome_email_sweep_idx").on(
      table.source,
      table.welcomeEmailSentAt,
      table.createdAt,
    ),
  ],
);

/**
 * Yielded Auth owns identifiers, credentials, sessions, pending authentication
 * and passkey ceremonies. The application owns `user` above; Yielded maps it as
 * the subject table so user IDs remain stable.
 */
/**
 * Baseline assurance for accounts without an authenticator app. Passkeys are
 * the primary credential; enabling TOTP adds a required second factor.
 */
export const authRequirement: Sessions.AuthenticationRequirement = authenticationRequirement(false);

/**
 * The subject columns the auth persistence layer reads when deciding whether an
 * account can satisfy multi-factor sign-in.
 */
export type AuthSubjectFactors = {
  readonly totpEnabled?: boolean | null;
  readonly passkeyEnabled?: boolean | null;
};

/**
 * Whether an account has a factor that satisfies a tenant's MFA requirement.
 * Passkeys are the baseline primary credential, so either a passkey or an
 * authenticator app is enough for tenant access.
 */
export const hasMfaFactor = (subject: AuthSubjectFactors): boolean =>
  subject.totpEnabled === true || subject.passkeyEnabled === true;

/**
 * The sign-in requirement for one subject row. Only TOTP changes the shape of
 * the requirement: when it is enabled, a passkey or SSO credential must be
 * combined with a current authenticator code.
 */
export const authRequirementForSubject = (
  subject: AuthSubjectFactors,
): Sessions.AuthenticationRequirement => authenticationRequirement(subject.totpEnabled === true);

