/**
 * Drizzle mapping consumed by the library's native TOTP persistence. The
 * credential row is the shared auth credential authority, so session revision
 * vectors automatically include an enabled authenticator.
 */
export const totpMapping: any = {
  moduleId: TOTP_MODULE_ID,
  policy: TOTP_POLICY,
  constraints: {
    factor: "unique(scope)",
    credential: "unique(credentialId)",
    subject: "unique(id)",
  },
  subjectIds: {
    toNative: (subjectId: string) => subjectId,
    toSubject: (subjectId: string) => subjectId,
  },
  subject: {
    table: user,
    id: "id",
    securityRevision: "authRevision",
    factorEnabled: "totpEnabled",
    activeCondition: sql`${user.disabled} = false`,
    encodeEnabled: (enabled: boolean) => enabled,
    decodeRequirement: (row: Readonly<Record<string, unknown>>) =>
      authenticationRequirement(hasMfaFactor(row)),
    requirementColumns: ["totpEnabled", "passkeyEnabled", "disabled"],
  },
  factor: {
    table: authTotpFactors,
    scope: "scope",
    state: "state",
    version: "version",
    encodeInsert: (value: { scope: string; state: string; version: string }) => value,
  },
  credential: {
    table: authCredentials,
    id: "credentialId",
    subjectId: "subjectId",
    revision: "revision",
    status: "active",
    activeCondition: sql`${authCredentials.active} = true`,
    encodeStatus: (active: boolean) => active,
    encodeInsert: (value: {
      credentialId: string;
      subjectId: string;
      revision: string;
      active: boolean;
    }) => value,
  },
  engineNowMillis: sql`cast(unix_timestamp(current_timestamp(3)) * 1000 as signed)`,
};

